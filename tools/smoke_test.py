"""End-to-end smoke test: every page, the job lifecycle and the money flow.

Run it after any change:

    .venv\\Scripts\\python.exe tools\\smoke_test.py

It uses Django's test client against the real (development) database, so it also
proves the templates render and the queries work. It is deliberately not a unit
test: the point is to catch a broken page before you demo it.
"""
import os
import sys
from io import BytesIO
from pathlib import Path

# Run from anywhere: make the project root importable.
sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

os.environ.setdefault("DJANGO_SETTINGS_MODULE", "config.settings")
os.environ.setdefault("DJANGO_ALLOWED_HOSTS", "testserver,127.0.0.1,localhost")

import django  # noqa: E402

django.setup()

from django.core.files.uploadedfile import SimpleUploadedFile  # noqa: E402
from django.core.management import call_command  # noqa: E402
from django.test import Client  # noqa: E402

from apps.accounts.models import User  # noqa: E402
from apps.billing.models import Invoice  # noqa: E402
from apps.credits.services import ensure_account  # noqa: E402
from apps.printing.models import PrintJob  # noqa: E402

PASSWORD = os.environ.get("SMOKE_PASSWORD", "esprints123")
failures = []
checked = 0


def check(label, response, expected=(200,)):
    global checked
    checked += 1
    status = getattr(response, "status_code", None)
    if status not in expected:
        failures.append(f"{label}: HTTP {status} (expected {expected})")
        print(f"  FAIL {label} -> {status}")
        body = getattr(response, "content", b"")[:4000].decode("utf-8", "replace")
        if "Traceback" in body or "Error" in body:
            print("   ", body[-1200:])
    else:
        print(f"  ok   {label}")


def make_pdf(pages=2):
    from reportlab.lib.pagesizes import A4
    from reportlab.pdfgen import canvas

    buffer = BytesIO()
    pdf = canvas.Canvas(buffer, pagesize=A4)
    for number in range(1, pages + 1):
        pdf.setFont("Helvetica-Bold", 28)
        pdf.drawString(60, 700, f"Smoke test page {number}")
        pdf.setFont("Helvetica", 12)
        pdf.drawString(60, 660, "Generated by tools/smoke_test.py")
        pdf.showPage()
    pdf.save()
    return buffer.getvalue()


def main():
    print("\n== pages ==")
    admin = User.objects.filter(is_staff=True).order_by("pk").first()
    member = User.objects.filter(role=User.Role.MEMBER, is_active=True).order_by("pk").first()
    if not admin or not member:
        print("No seeded users. Run: python manage.py seed_demo")
        return 1
    if not member.has_usable_password():
        member.set_password(PASSWORD)
        member.save()
    if not admin.has_usable_password():
        admin.set_password(PASSWORD)
        admin.save()

    anonymous = Client()
    check("login page (anonymous)", anonymous.get("/login/"))
    check("/ redirects to login", anonymous.get("/"), expected=(302,))
    check("health", anonymous.get("/health/"))
    check("dashboard blocked (anonymous)", anonymous.get("/manage/"), expected=(302,))
    check("invite page rejects a bad token",
          anonymous.get("/invite/abc/invalid-token/"), expected=(400,))

    staff = Client()
    assert staff.login(username=admin.student_no, password=PASSWORD), "admin login failed"
    for path in ["/manage/", "/manage/members/", "/manage/members/new/",
                 f"/manage/members/{member.pk}/", f"/manage/members/{member.pk}/edit/",
                 "/manage/plans/", "/manage/plans/new/", "/manage/invoices/",
                 "/manage/queue/", "/manage/jobs/", "/manage/jobs/?status=PRINTED",
                 "/manage/jobs/?export=csv", "/manage/settings/"]:
        check(f"(staff) {path}", staff.get(path))

    student = Client()
    assert student.login(username=member.student_no, password=PASSWORD), "member login failed"
    for path in ["/home/", "/jobs/", "/jobs/new/", "/credits/", "/billing/",
                 "/billing/topup/", "/profile/"]:
        check(f"(member) {path}", student.get(path))

    print("\n== job lifecycle (printing to PDF) ==")
    account = ensure_account(member)
    balance_before = account.balance_credits
    upload = SimpleUploadedFile("smoke-test.pdf", make_pdf(2),
                                content_type="application/pdf")
    response = student.post("/jobs/new/", {
        "document": upload, "colour_mode": "MONO", "sides": "SIMPLEX",
        "paper": "A4", "copies": 1}, follow=True)
    check("upload a 2-page PDF", response)

    job = PrintJob.objects.filter(member=member).order_by("-created_at").first()
    if not job:
        failures.append("job was not created")
        return report()

    print(f"  job {job.code}: {job.page_count} pages, {job.cost_credits} credits")
    if job.cost_credits != 20:
        failures.append(f"pricing: expected 20 credits, got {job.cost_credits}")

    account.refresh_from_db()
    if account.held_credits != 0:
        failures.append("confirming should not have happened yet")

    check("job detail page", student.get(f"/jobs/{job.public_id}/"))
    check("confirm the job", student.post(f"/jobs/{job.public_id}/", follow=True))

    job.refresh_from_db()
    account.refresh_from_db()
    if job.status != PrintJob.Status.QUEUED:
        failures.append(f"after confirm: status {job.status}, expected QUEUED")
    if account.held_credits != job.cost_credits:
        failures.append(f"after confirm: held {account.held_credits}, "
                        f"expected {job.cost_credits}")

    call_command("run_worker", "--once", verbosity=0)
    job.refresh_from_db()
    account.refresh_from_db()
    print(f"  after worker: {job.status}, output={job.output_file or 'none'}")
    if job.status != PrintJob.Status.PRINTED:
        failures.append(f"after worker: status {job.status}, expected PRINTED")
    if account.held_credits != 0:
        failures.append("after printing: a reservation is still held")
    if account.balance_credits != balance_before - job.cost_credits:
        failures.append(f"after printing: balance {account.balance_credits}, "
                        f"expected {balance_before - job.cost_credits}")
    if not job.output_file:
        failures.append("no printed output file was produced")
    else:
        from pathlib import Path
        from django.conf import settings
        output = Path(settings.MEDIA_ROOT) / job.output_file
        print(f"  printed output: {output} ({'exists' if output.exists() else 'MISSING'})")
        if not output.exists():
            failures.append("printed output file is missing on disk")
    check("output download", student.get(f"/jobs/{job.public_id}/output/"))

    print("\n== invoice flow ==")
    # Unique per run: this database persists between runs, and the duplicate
    # control (correctly) refuses to reuse a transaction ID ever again.
    from datetime import datetime
    txn_id = "SMOKE" + datetime.now().strftime("%d%H%M%S%f")[:12]
    check("create an invoice",
          student.post("/billing/topup/", {"amount": "20.00"}, follow=True))
    invoice = Invoice.objects.filter(member=member).order_by("-created_at").first()
    print(f"  invoice {invoice.reference}: {invoice.amount_rand} = {invoice.credits} credits")
    if invoice.credits != 200:
        failures.append(f"invoice credits: expected 200, got {invoice.credits}")

    check("submit the transaction ID", student.post(
        f"/billing/{invoice.reference}/submit/",
        {"momo_txn_id": txn_id, "payer_phone": member.phone}, follow=True))
    invoice.refresh_from_db()
    if invoice.status != Invoice.Status.AWAITING_APPROVAL:
        failures.append(f"after submit: {invoice.status}")

    check("review page", staff.get(f"/manage/invoices/{invoice.reference}/"))
    balance_before = account.balance_credits
    check("approve", staff.post(f"/manage/invoices/{invoice.reference}/approve/",
                                follow=True))
    invoice.refresh_from_db()
    account.refresh_from_db()
    if invoice.status != Invoice.Status.APPROVED:
        failures.append(f"after approve: {invoice.status}")
    if account.balance_credits != balance_before + invoice.credits:
        failures.append(f"after approval: balance {account.balance_credits}, "
                        f"expected {balance_before + invoice.credits}")

    check("approve again (must be idempotent)",
          staff.post(f"/manage/invoices/{invoice.reference}/approve/", follow=True))
    account.refresh_from_db()
    if account.balance_credits != balance_before + invoice.credits:
        failures.append("double approval changed the balance")

    print("\n== duplicate transaction control ==")
    student.post("/billing/topup/", {"amount": "10.00"}, follow=True)
    fresh = (Invoice.objects
             .filter(member=member, status=Invoice.Status.AWAITING_PAYMENT)
             .order_by("-created_at").first())
    if fresh is None:
        failures.append("could not create a second invoice to test duplicates")
    else:
        student.post(f"/billing/{fresh.reference}/submit/",
                     {"momo_txn_id": txn_id,
                      "payer_phone": member.phone}, follow=True)
        fresh.refresh_from_db()
        if fresh.status == Invoice.Status.AWAITING_APPROVAL:
            failures.append("a duplicate transaction ID was accepted")
        else:
            print(f"  ok   duplicate transaction ID rejected "
                  f"(stays {fresh.get_status_display()})")

    print("\n== invitation flow ==")
    from apps.accounts.services import invite_url

    new_number = "2022" + str(datetime.now().microsecond).zfill(4)[:4]
    staff.post("/manage/members/new/", {
        "student_no": new_number,
        "first_name": "Invite",
        "last_name": "Test",
        "email": f"{new_number}@student.uneswa.ac.sz",
        "phone": "+26876000001",
        "role": "MEMBER",
    }, follow=True)
    invited = User.objects.filter(student_no=new_number).first()
    if invited is None:
        failures.append("admin could not create a member")
    else:
        if invited.has_usable_password():
            failures.append("a new member should not have a password yet")
        link = invite_url(invited)
        path = link.replace("http://127.0.0.1:8000", "")
        print(f"  invitation: {path[:64]}...")
        check("invitation link opens", anonymous.get(path))
        check("set the password", anonymous.post(path, {
            "password1": "new-member-pass-9",
            "password2": "new-member-pass-9"}, follow=True))
        invited.refresh_from_db()
        if not invited.has_usable_password():
            failures.append("password was not saved from the invitation")
        if invited.invitation_accepted_at is None:
            failures.append("invitation was not marked as accepted")
        fresh = Client()
        if not fresh.login(username=new_number, password="new-member-pass-9"):
            failures.append("the new member cannot sign in")
        else:
            check("new member dashboard", fresh.get("/home/"))

    print("\n== ledger ==")
    call_command("check_credits", verbosity=0)
    return report()


def report():
    print(f"\n{checked} page checks, {len(failures)} problem(s)")
    if failures:
        print("\nFAILURES")
        for item in failures:
            print(f"  - {item}")
        return 1
    print("All good.")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except AssertionError as exc:
        print(f"\nSETUP FAILED: {exc}")
        sys.exit(1)
